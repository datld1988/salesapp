    AFTER INSERT OR UPDATE OR DELETE
ON AD_TEMPLATE
FOR EACH ROW
BEGIN
    INSERT INTO HIS_TEMPLATE (
        ID,
        CODE, FILE_TYPE, FILE_CONTENT, TEXT_CONTENT, DESCRIPTION, BOOKMARKS,
        CREATED_DATE, CREATED_BY, MODIFIED_DATE, MODIFIED_BY, HIS_CREATED_DATE
    )
    VALUES
    (
        SYS_GUID(),
        :OLD.CODE, :OLD.FILE_TYPE, :OLD.FILE_CONTENT, :OLD.TEXT_CONTENT, :OLD.DESCRIPTION, :OLD.BOOKMARKS,
        :OLD.CREATED_DATE, :OLD.CREATED_BY, :OLD.MODIFIED_DATE, :OLD.MODIFIED_BY, SYSDATE
    );
END;

