-- LOG TRUY CẬP TỪ ỨNG DỤNG VÀ NGƯỜI DÙNG
CREATE TABLE UNIFORM_LOG.LOG_ACTION
(
  ID                   VARCHAR2(50 BYTE) NOT NULL,
  BROWSER              VARCHAR2(100 BYTE),
  IP_CLIENT            VARCHAR2(100 BYTE),
  IP_SERVER            VARCHAR2(100 BYTE),
  CONTROLLER_NAME      VARCHAR2(512 BYTE),
  ACTION_NAME          VARCHAR2(512 BYTE),
  DESCRIPTION          VARCHAR2(4000 BYTE),
  OTHERS               VARCHAR2(4000 BYTE),
  USERNAME             VARCHAR2(512 BYTE),
  DURATION_TIME        NUMBER(5),
  OBJECT_ID            VARCHAR2(50 BYTE),
  LOG_TIME             DATE,
  MACHINE_NAME_SERVER  VARCHAR2(100 BYTE),
  CONSTRAINT PK_LOG_ACTION PRIMARY KEY (ID)
);
COMMENT ON TABLE UNIFORM_LOG.LOG_ACTION IS 'Log request từ client';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.ID IS 'Mã PK';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.BROWSER IS 'Thông tin trình duyệt';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.IP_CLIENT IS 'IP Client';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.IP_SERVER IS 'IP Server';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.CONTROLLER_NAME IS 'Mã PK';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.ACTION_NAME IS 'Mã PK';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.DESCRIPTION IS 'Mô tả';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.OTHERS IS 'Thông tin khác';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.USERNAME IS 'Tên người dùng';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.DURATION_TIME IS 'Thời gian xử lý';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.OBJECT_ID IS 'Mã đối tượng truy vấn';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.LOG_TIME IS 'Thời gian log';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ACTION.MACHINE_NAME_SERVER IS 'Tên máy chủ';

-- LOG TRUY VẤN I/O VỚI ESB
CREATE TABLE UNIFORM_LOG.LOG_ESB
(
  REQUEST_ID       VARCHAR2(50 BYTE) NOT NULL,
  SERVICE_CODE     VARCHAR2(200 BYTE),
  INPUT_DATA       CLOB,
  OUTPUT_DATA      CLOB,
  DURATION_TIME    NUMBER(18),
  USER_REQUEST     VARCHAR2(50 BYTE),
  OBJECT_ID        VARCHAR2(50 BYTE),
  REF_OBJECT1_ID    VARCHAR2(50 BYTE),
  REF_OBJECT2_ID    VARCHAR2(50 BYTE),
  REF_OBJECT3_ID    VARCHAR2(50 BYTE),
  REQUEST_DATE     DATE,
  RESPONSE_CODE    VARCHAR2(50 BYTE),
  RESPONSE_MSG     VARCHAR2(4000 BYTE),
  IS_SUCCESS       NUMBER(1),
  CONSTRAINT PK_LOG_ESB PRIMARY KEY (REQUEST_ID)
);
COMMENT ON TABLE UNIFORM_LOG.LOG_ESB IS 'Log In/Out ESB';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.REQUEST_ID IS 'RequestId sang ESB';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.SERVICE_CODE IS 'Mã dịch vụ';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.INPUT_DATA IS 'Log input';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.OUTPUT_DATA IS 'Log output';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.DURATION_TIME IS 'Thời gian request';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.USER_REQUEST IS 'Tên user request';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.OBJECT_ID IS 'Mã đối tượng dữ liệu sử dụng';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.REF_OBJECT1_ID IS 'Mã đối tượng 1';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.REF_OBJECT2_ID IS 'Mã đối tượng 2';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.REF_OBJECT3_ID IS 'Mã đối tượng 3';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.REQUEST_DATE IS 'Thời điểm request';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.RESPONSE_CODE IS 'Mã trả về';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.RESPONSE_MSG IS 'Message trả về';
COMMENT ON COLUMN UNIFORM_LOG.LOG_ESB.IS_SUCCESS IS 'Thành công';